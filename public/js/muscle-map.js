/* *Load SVG* */

async function loadSvg(

    path,

    containerId

) {

    const container =

        document.getElementById(

            containerId

        );



    if (!container) {

        console.error(

            `Container not found: #${containerId}`

        );

        return false;

    }



    try {

        console.log(

            `Loading SVG: ${path}`

        );



        const response =

            await fetch(

                path

            );



        if (!response.ok) {

            throw new Error(

                `HTTP ${response.status}`

            );

        }



        const svgText =

            await response.text();



        if (

            !svgText.includes(

                "<svg"

            )

        ) {

            throw new Error(

                "File is not a valid SVG"

            );

        }



        container.innerHTML =

            svgText;



        const svg =

            container.querySelector(

                "svg"

            );



        if (!svg) {

            throw new Error(

                "SVG element not found"

            );

        }



        svg.classList.add(

            "anatomy-svg"

        );



        svg.removeAttribute(

            "width"

        );



        svg.removeAttribute(

            "height"

        );



        console.log(

            `Loaded successfully: ${path}`

        );



        return true;

    }

    catch (error) {

        console.error(

            `Failed to load ${path}:`,

            error

        );



        container.innerHTML = `

            <div class="map-error">

                <i class="bi bi-exclamation-triangle-fill me-2"></i>

                <strong>

                    Unable to load anatomy

                </strong>

                <br>

                ${path}

                <br>

                ${error.message}

            </div>

        `;



        return false;

    }

}





