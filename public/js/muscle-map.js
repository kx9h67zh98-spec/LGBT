/* *YouTube URL* */

function getYouTubeEmbedUrl(

    videoUrl

) {

    if (!videoUrl) {

        return "";

    }



    try {

        const url =

            new URL(

                videoUrl

            );



        let videoId =

            "";



        /* *youtu.be* */

        if (

            url.hostname.includes(

                "youtu.be"

            )

        ) {

            videoId =

                url.pathname

                    .split("/")

                    .filter(Boolean)[0];

        }



        /* *youtube.com* */

        else if (

            url.hostname.includes(

                "youtube.com"

            )

        ) {



            /* *Watch* */

            if (

                url.pathname ===

                "/watch"

            ) {

                videoId =

                    url.searchParams.get(

                        "v"

                    );

            }



            /* *Shorts* */

            else if (

                url.pathname.startsWith(

                    "/shorts/"

                )

            ) {

                videoId =

                    url.pathname

                        .split("/")

                        .filter(Boolean)[1];

            }



            /* *Embed* */

            else if (

                url.pathname.startsWith(

                    "/embed/"

                )

            ) {

                videoId =

                    url.pathname

                        .split("/")

                        .filter(Boolean)[1];

            }

        }



        if (!videoId) {

            return "";

        }



        return (

            `https://www.youtube.com/embed/${videoId}`

        );

    }

    catch (error) {

        console.error(

            "Invalid YouTube URL:",

            videoUrl

        );



        return "";

    }

}





